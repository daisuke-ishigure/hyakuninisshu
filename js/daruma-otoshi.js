    if (FIXED_NUM !== null) {
      poem = POEMS.find(p => p.num === FIXED_NUM) || POEMS[0];
    } else {
      let idx;
      do { idx = Math.floor(Math.random() * POEMS.length); }
      while (idx === lastPoemIdx && POEMS.length > 1);
      lastPoemIdx = idx;
      poem = POEMS[idx];
    }

    // ダミー設定: poem.dummies を基本とし、HTML側設定で上書き可能（最大3か所）
    // poem.dummies 形式: [{ idx: 2, phrase: 'xxx' }, { idx: 4, phrase: 'yyy' }]
    const _poemDummies = Array.isArray(poem.dummies) ? poem.dummies.slice(0, 3) : [];
    const _htmlIdxs    = Array.isArray(window.DARUMA_DUMMY_IDXS) && window.DARUMA_DUMMY_IDXS.length
      ? window.DARUMA_DUMMY_IDXS : null;
    const _htmlPhrases = Array.isArray(window.DARUMA_DUMMIES) && window.DARUMA_DUMMIES.length
      ? window.DARUMA_DUMMIES : null;

