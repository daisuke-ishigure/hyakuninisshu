function getTodayString() {
    const d = new Date();
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

function getTodayResult() {
    if (localStorage.getItem('omikuji_date') === getTodayString()) {
        const idx = parseInt(localStorage.getItem('omikuji_result_index'), 10);
        if (!isNaN(idx) && idx >= 0 && idx < hyakuninIsshu.length) {
            return { result: hyakuninIsshu[idx], index: idx };
        }
    }
    return null;
}

function saveTodayResult(index) {
    localStorage.setItem('omikuji_date', getTodayString());
    localStorage.setItem('omikuji_result_index', String(index));
}

