  function commit(els) {
    [].concat(els).forEach(el => {
      const cs = window.getComputedStyle(el);
      el.style.transform = (cs.transform === 'none') ? '' : cs.transform;
      el.style.opacity   = cs.opacity;
      el.getAnimations().forEach(a => a.cancel());
    });
  }
  function reset(els) {
    [].concat(els).forEach(el => {
      el.getAnimations().forEach(a => a.cancel());
      el.style.transform = '';
      el.style.opacity   = '';
    });
  }

