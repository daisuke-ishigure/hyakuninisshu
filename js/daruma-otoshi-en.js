  function animateViewBox(fromMinY, fromH, toMinY, toH, duration) {
    const vb  = svg.getAttribute('viewBox').split(' ').map(Number);
    const vbX = vb[0], vbW = vb[2];
    const start = performance.now();
    function eio(t) { return t < 0.5 ? 2*t*t : -1 + (4 - 2*t)*t; }
    function step(now) {
      const e    = eio(Math.min((now - start) / duration, 1));
      const minY = Math.round(fromMinY + (toMinY - fromMinY) * e);
      const h    = Math.round(fromH    + (toH    - fromH)    * e);
      svg.setAttribute('viewBox', `${vbX} ${minY} ${vbW} ${h}`);
      if (e < 1) requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
  }

